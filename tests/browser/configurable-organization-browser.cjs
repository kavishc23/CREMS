const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.CREMS_TEST_URL || 'http://127.0.0.1:5181';
const out = process.env.CREMS_TEST_ARTIFACTS || 'tmp/configurable-organization-browser';
const branchId = '11111111-1111-1111-1111-111111111111';
let document, writes = [], failSave = false;
const branches = [{ id: branchId, name: 'Suva', code: 'SUV', isActive: true, divisionIds: [] }];
const json = value => JSON.parse(JSON.stringify(value));
(async () => {
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/api/**', async route => {
    const req = route.request(), path = new URL(req.url()).pathname.replace(/^\/api/, '');
    if (!new URL(req.url()).pathname.startsWith('/api/')) return route.continue();
    if (req.method() !== 'GET') {
      const body = req.postData() ? req.postDataJSON() : null;
      writes.push({ path, body });
      if (path === '/organization/setup') {
        if (failSave) return route.fulfill({ status: 409, json: { message: 'These settings changed since setup was opened. Reopen the wizard.' } });
        document = json(body); document.id ||= '22222222-2222-2222-2222-222222222222'; document.revision = 'saved';
        document.services.forEach((s, si) => { s.id ||= `service-${si}`; s.categories.forEach((c, ci) => { c.id ||= `category-${si}-${ci}`; c.templates.forEach((t, ti) => { t.id ||= `template-${si}-${ci}-${ti}`; }); }); });
        branches[0].divisionIds = [document.id];
        return route.fulfill({ json: { id: document.id } });
      }
      return route.fulfill({ status: 204 });
    }
    if (path.startsWith('/organization/setup/')) return route.fulfill({ json: document });
    if (path === '/organization/operating-context') return route.fulfill({ json: document ? [{ branchId, divisionId: document.id, branchName: 'Suva', divisionName: document.division.name, acceptsBookings: true, flow: document.flow, periods: [], exceptions: [], services: document.services.map(s => ({ ...s.service, id: s.id, isBookable: true, categories: s.categories.map(c => ({ ...c.category, fields: c.attributes, templates: c.templates })) })) }] : [] });
    if (path === '/divisions') return route.fulfill({ json: document ? [{ ...document.division, id: document.id, capabilities: 3, services: document.services.map(s => ({ ...s.service, id: s.id })) }] : [] });
    if (path.endsWith('/booking-flow')) return route.fulfill({json:{id:document.id,name:document.division.name,flow:document.flow,...document.division}});
    if (path === '/branches') return route.fulfill({ json: branches });
    if (path === '/asset-categories') return route.fulfill({ json: document ? document.services.flatMap(s => s.categories.map(c => ({ ...c.category, id: c.id, divisionId: document.id, serviceOfferingId: s.id, attributeDefinitions: c.attributes }))) : [] });
    if (path.includes('/configuration')) return route.fulfill({ json: { periods: [], exceptions: [], services: [] } });
    if (path === '/administration/settings') return route.fulfill({ json: [{ id: 'vat', key: 'rentals.vatRate', value: '12.5', category: 'Rentals', description: 'VAT rate' }] });
    if (path === '/auth/session') return route.fulfill({ json: { id: 'admin', roles: ['SuperAdministrator'], fullName: 'Test staff' } });
    return route.fulfill({ json: [] });
  });
  await page.route('**/__configuration_test*', route => route.fulfill({ contentType: 'text/html', body: `<html><body><div id="root"></div><script type="module">
    import RefreshRuntime from '/@react-refresh'; RefreshRuntime.injectIntoGlobalHook(window); window.$RefreshReg$=()=>{}; window.$RefreshSig$=()=>type=>type; window.__vite_plugin_react_preamble_installed__=true;
    const {default:React}=await import('/node_modules/.vite/deps/react.js'); const {default:ReactDOM}=await import('/node_modules/.vite/deps/react-dom_client.js');
    const {ThemeProvider,CssBaseline}=await import('/node_modules/.vite/deps/@mui_material.js'); const {staffTheme}=await import('/src/layout/staffTheme.ts');
    const {OrganizationWorkspacePage}=await import('/src/pages/OrganizationWorkspacePage.tsx'); const {AuthProvider}=await import('/src/auth/AuthContext.tsx');
    const role=new URL(location.href).searchParams.get('role')||'SuperAdministrator';
    ReactDOM.createRoot(document.getElementById('root')).render(React.createElement(AuthProvider,null,React.createElement(ThemeProvider,{theme:staffTheme},React.createElement(CssBaseline),React.createElement(OrganizationWorkspacePage,{userRoles:[role]}))));
  </script></body></html>` }));
  try {
    await page.goto(base + '/__configuration_test');
    await page.getByRole('tab', { name: 'Business setup', exact: true }).click();
    await page.getByRole('button', { name: 'Add business / division', exact: true }).click();
    let dialog = page.locator('[role=dialog][aria-labelledby=division-setup-title]');
    await dialog.getByLabel('Division name', { exact: false }).fill('Carpenters Test Equipment');
    await dialog.getByLabel('Division code', { exact: false }).fill('TEST_EQUIP');
    await dialog.getByRole('button', { name: '+ Heavy machinery', exact: true }).click();
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    await dialog.getByLabel('Suva', { exact: true }).check();
    await dialog.getByRole('button', { name: 'Add customer question', exact: true }).click();
    await dialog.getByLabel('Question label', { exact: false }).fill('Worksite access');
    await dialog.getByLabel('Answer type', { exact: true }).click(); await page.getByRole('option', { name: 'Choice', exact: true }).click();
    await dialog.getByLabel('Choices (one per line)', { exact: false }).fill('Open site\nRestricted site');
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    await dialog.getByLabel('Usage interval', { exact: false }).fill('250');
    await dialog.getByLabel('Calendar interval in days', { exact: false }).fill('90');
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    await dialog.getByLabel('Record fuel / battery level', { exact: true }).uncheck();
    await dialog.getByRole('button', { name: 'Continue', exact: true }).click();
    await page.waitForTimeout(250);
    await page.screenshot({ path: out + '/review-desktop.png', fullPage: true });
    await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    const saved = writes.find(w => w.path === '/organization/setup').body;
    assert.equal(saved.division.name, 'Carpenters Test Equipment');
    assert.equal(saved.flow.customerFields[0].label, 'Worksite access');
    assert.deepEqual(saved.flow.customerFields[0].options, ['Open site', 'Restricted site']);
    assert.equal(saved.services[0].branchIds[0], branchId);
    assert.equal(JSON.parse(saved.services[0].service.maintenanceRulesJson).meterInterval, 250);
    assert.equal(JSON.parse(saved.services[0].service.inspectionRequirementsJson).tracksFuel, false);
    assert.equal(saved.services[0].categories[0].templates.length, 2);
    await page.getByRole('button', { name: 'Configure division', exact: true }).click();
    dialog = page.locator('[role=dialog][aria-labelledby=division-setup-title]');
    await dialog.getByRole('button', { name: /Customer requests/ }).click();
    await dialog.getByLabel('Question label', { exact: false }).waitFor();
    assert.equal(await dialog.getByLabel('Question label', { exact: false }).inputValue(), 'Worksite access');
    await dialog.getByRole('button', { name: /Review/ }).click();
    failSave = true;
    await dialog.getByRole('button', { name: 'Save configuration', exact: true }).click();
    await dialog.getByText(/These settings changed/).waitFor();
    assert.equal(await dialog.isVisible(), true, 'A failed save must preserve the editable wizard');
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('tab', { name: 'Communications', exact: true }).click();
    assert.equal(await page.getByRole('tab', { name: 'System health & audit', exact: true }).count(), 0);
    await page.getByRole('heading', { name: 'Customer notifications', exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Booking & pricing', exact: true }).click();
    for (const name of ['Booking & quotations', 'Fees & charges', 'Approval rules', 'Rental defaults']) await page.getByRole('tab', { name, exact: true }).waitFor();
    for (const role of ['BranchManager', 'RentalOfficer', 'MaintenanceOfficer', 'Administrator']) {
      await page.goto(base + '/__configuration_test?role=' + role);
      await page.getByText('Carpenters Test Equipment', { exact: true }).waitFor();
      await page.getByText('Heavy machinery hire', { exact: true }).click();
      await page.getByText('Worksite access *', { exact: true }).waitFor();
      assert.equal(await page.getByRole('button', { name: 'Add business / division', exact: true }).count(), 0);
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: out + '/branch-staff-mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'Staff settings must fit a phone viewport');
    await page.goto(base+'/__configuration_test');
    await page.getByRole('tab',{name:'Business setup',exact:true}).click();
    await page.getByRole('button',{name:'Configure division',exact:true}).click();
    const mobileDialog=page.locator('[role=dialog][aria-labelledby=division-setup-title]');
    await mobileDialog.getByRole('button',{name:/Asset fields & checks/}).click();
    await mobileDialog.getByLabel('Default asset type').waitFor();
    await page.waitForTimeout(250);
    await page.screenshot({path:out+'/setup-mobile.png',fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'Setup must fit a phone viewport');
    assert.deepEqual(errors, []);
    console.log('PASS guided setup payload, reload, stale-save feedback, retained settings, staff role views and mobile layout');
  } catch(error) { await page.screenshot({path:out+'/failure.png',fullPage:true}); console.error((await page.locator('body').innerText()).slice(0,2000)); throw error; } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
